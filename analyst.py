# EXECUTE ANALYSIS
# ============================================================

def execute_analysis(df, generated_code):

    try:

        generated_code = clean_generated_code(
            generated_code
        )

        forbidden_words = [

            "import ",

            "__import__",

            "os.",

            "sys.",

            "subprocess",

            "requests.",

            "urllib",

            "open(",

            "eval(",

            "exec(",

            "input(",

            "socket",

            "shutil",

            "pathlib"
        ]

        code_lower = generated_code.lower()

        for word in forbidden_words:

            if word.lower() in code_lower:

                return (
                    None,
                    None,
                    "Generated code contains blocked operation: "
                    + word
                )

        safe_builtins = {

            "len": len,

            "str": str,

            "int": int,

            "float": float,

            "round": round,

            "min": min,

            "max": max,

            "sum": sum,

            "abs": abs,

            "sorted": sorted,

            "range": range,

            "list": list,

            "dict": dict,

            "set": set,

            "enumerate": enumerate
        }

        safe_globals = {

            "__builtins__": safe_builtins,

            "pd": pd
        }

        safe_locals = {

            "df": df.copy(),

            "pd": pd
        }

        exec(
            generated_code,
            safe_globals,
            safe_locals
        )

        result = safe_locals.get(
            "result"
        )

        if result is None:

            return (
                None,
                None,
                "Generated code did not create "
                "a result variable."
            )

        fig = create_visualization(
            result
        )

        return (
            result,
            fig,
            None
        )

    except Exception as e:

        return (
            None,
            None,
            str(e)
        )


# ============================================================
# VISUALIZATION
# ============================================================

def create_visualization(result):

    try:

        if isinstance(
            result,
            pd.DataFrame
        ):

            if result.empty:
                return None

            numeric_columns = (
                result
                .select_dtypes(
                    include="number"
                )
                .columns
                .tolist()
            )

            if (
                len(result.columns) >= 2
                and len(numeric_columns) >= 1
            ):

                x_column = result.columns[0]

                y_column = numeric_columns[0]

                return px.bar(

                    result,

                    x=x_column,

                    y=y_column,

                    title="Analysis Result"
                )

        elif isinstance(
            result,
            pd.Series
        ):

            if result.empty:
                return None

            data = result.reset_index()

            if data.shape[1] >= 2:

                return px.bar(

                    data,

                    x=data.columns[0],

                    y=data.columns[1],

                    title="Analysis Result"
                )

    except Exception:

        return None

    return None


