# ============================================================
# ENVIRONMENT
# ============================================================

load_dotenv()


# ============================================================
# GROQ CLIENT
# ============================================================

def get_groq_client():

    api_key = os.getenv("GROQ_API_KEY")

    if not api_key:
        raise ValueError(
            "GROQ_API_KEY is not set. "
            "Please add your Groq API key to .env"
        )

    return Groq(api_key=api_key)


# ============================================================
# CLEAN CODE
# ============================================================

def clean_generated_code(code):

    if code is None:
        return ""

    code = str(code).strip()

    # Remove markdown fences
    code = re.sub(
        r"```python",
        "",
        code,
        flags=re.IGNORECASE
    )

    code = re.sub(
        r"```",
        "",
        code
    )

    lines = code.splitlines()

    cleaned_lines = []

    for line in lines:

        stripped = line.strip()

        # Remove imports generated by Groq
        if stripped.startswith("import "):
            continue

        if stripped.startswith("from "):
            continue

        cleaned_lines.append(line)

    return "\n".join(
        cleaned_lines
    ).strip()


