def generate_answer(question, result):

    client = get_groq_client()

    if isinstance(
        result,
        pd.DataFrame
    ):

        result_text = result.to_string(
            index=False
        )

    elif isinstance(
        result,
        pd.Series
    ):

        result_text = result.to_string()

    else:

        result_text = str(
            result
        )

    prompt = (

        "You are an AI data analyst.\n\n"

        "USER QUESTION:\n"
        + question
        + "\n\n"

        "ACTUAL COMPUTED RESULT:\n"
        + result_text
        + "\n\n"

        "Answer using ONLY the actual computed result.\n\n"

        "Rules:\n"
        "1. Do not invent numbers.\n"
        "2. Do not change numbers.\n"
        "3. Do not make unsupported assumptions.\n"
        "4. Clearly state the important result.\n"
        "5. Keep the answer concise.\n"
        "6. Mention growth percentage when available.\n"
        "7. Mention previous and current values when available.\n"
        "8. If data is unavailable, say so clearly."
    )

    response = client.chat.completions.create(

        model="llama-3.3-70b-versatile",

        messages=[

            {
                "role": "system",
                "content": (
                    "Explain computed data accurately. "
                    "Never invent numerical results."
                )
            },

            {
                "role": "user",
                "content": prompt
            }

        ],

        temperature=0
    )

    return response.choices[0].message.content.strip()