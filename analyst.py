        + sample_data
        + "\n\n"

        "USER QUESTION:\n"
        + question
        + "\n\n"

        "YOUR TASK:\n"
        "Generate Python/Pandas code that answers "
        "the user's question using the REAL dataframe.\n\n"

        "IMPORTANT RULES:\n"
        "1. The dataframe already exists as df.\n"
        "2. Pandas is already available as pd.\n"
        "3. Do NOT write import statements.\n"
        "4. Do NOT write import pandas as pd.\n"
        "5. Do NOT load files.\n"
        "6. Do NOT create fake data.\n"
        "7. Do NOT invent values.\n"
        "8. Do NOT use print().\n"
        "9. Do NOT use input().\n"
        "10. Do NOT use exec().\n"
        "11. Do NOT use eval().\n"
        "12. Do NOT use web requests.\n"
        "13. Use only columns that exist.\n"
        "14. Store the final answer in a variable called result.\n"
        "15. Return ONLY executable Python code.\n"
        "16. Do not return markdown.\n"
        "17. Do not explain the code.\n\n"

        "DATE RULES:\n"
        "If the question involves dates, months, quarters, "
        "years, growth, trends, or previous periods, "
        "identify the appropriate date column and use "
        "pd.to_datetime().\n\n"

        "IMPORTANT QUARTER GROWTH RULE:\n"
        "If the user asks: Which region grew fastest last quarter?\n\n"

        "You must:\n"
        "1. Find the date column.\n"
        "2. Convert the date column to datetime.\n"
        "3. Create a quarter using .dt.to_period('Q').\n"
        "4. Find the latest quarter in the dataset.\n"
        "5. Find the previous quarter.\n"
        "6. Calculate sales by Region for the latest quarter.\n"
        "7. Calculate sales by Region for the previous quarter.\n"
        "8. Calculate percentage growth.\n"
        "9. Ignore regions where previous sales are zero.\n"
        "10. Sort by growth percentage descending.\n"
        "11. Return the fastest-growing region.\n\n"

        "The result should contain these fields:\n"
        "Region\n"
        "Previous_Sales\n"
        "Current_Sales\n"
        "Growth_Percentage\n\n"

        "Example quarter logic:\n\n"

        "df['Order_Date'] = pd.to_datetime(df['Order_Date'])\n\n"

        "df['Quarter'] = df['Order_Date'].dt.to_period('Q')\n\n"

        "latest_quarter = df['Quarter'].max()\n\n"

        "previous_quarter = latest_quarter - 1\n\n"

        "current_sales = (\n"
        "    df[df['Quarter'] == latest_quarter]\n"
        "    .groupby('Region')['Sales']\n"
        "    .sum()\n"
        ")\n\n"

        "previous_sales = (\n"
        "    df[df['Quarter'] == previous_quarter]\n"
        "    .groupby('Region')['Sales']\n"
        "    .sum()\n"
